import {chromium} from '@playwright/test';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto('http://127.0.0.1:4321/',{waitUntil:'networkidle'});
await page.screenshot({path:'artifacts/home-desktop.png',fullPage:true});
await page.goto('http://127.0.0.1:4321/admin/',{waitUntil:'networkidle'});
await page.screenshot({path:'artifacts/admin-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'artifacts/admin-mobile.png',fullPage:true});
console.log(JSON.stringify({browserErrors:errors,adminMobileOverflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)}));
await browser.close();
